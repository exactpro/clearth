package com.exactprosystems.clearth.woodpecker.utils;

import org.apache.commons.io.input.BOMInputStream;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * 30 July 2018
 */
public class WoodpeckerFileUtils
{
	public static BufferedReader newBufferedReaderIgnoresBom(Path path) throws IOException
	{
		InputStream is = new BOMInputStream(Files.newInputStream(path));
		return new BufferedReader(new InputStreamReader(is, StandardCharsets.UTF_8));
	}
}
